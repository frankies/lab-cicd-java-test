#!/bin/bash

set -euo pipefail
set -x

DB_USERNAME="${DB_USERNAME:-app}"
DB_DATABASE="${DB_DATABASE:-appdb}"
DB_PASSWORD="${DB_PASSWORD:-secret}"
DB_SCHEMA="${DB_SCHEMA:-$DB_USERNAME}"

psql -e -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
-- CREATE GROUP ROLE
CREATE ROLE develop WITH INHERIT REPLICATION;
GRANT pg_monitor, pg_signal_backend, pg_read_server_files, pg_write_server_files, pg_execute_server_program TO develop;

CREATE ROLE admin WITH NOLOGIN SUPERUSER NOINHERIT CREATEDB CREATEROLE NOREPLICATION;

-- CREATE USER ROLE
CREATE ROLE $DB_USERNAME WITH LOGIN PASSWORD '$DB_PASSWORD';
GRANT admin, develop TO $DB_USERNAME;

-- CREATE DATABASE
CREATE DATABASE $DB_DATABASE OWNER $DB_USERNAME;
REVOKE ALL PRIVILEGES ON DATABASE $DB_DATABASE FROM public;
GRANT ALL PRIVILEGES ON DATABASE $DB_DATABASE TO $DB_USERNAME;

-- REVOKE from public
REVOKE ALL ON DATABASE postgres FROM public;
GRANT CONNECT, TEMPORARY ON DATABASE POSTGRES TO public;

-- CONNECT TO DB_DATABASE
\c $DB_DATABASE

-- CREATE SCHEMA
REVOKE ALL PRIVILEGES ON SCHEMA public FROM public;
GRANT CREATE, USAGE ON SCHEMA public to $DB_USERNAME;
CREATE SCHEMA $DB_SCHEMA AUTHORIZATION $DB_USERNAME;
ALTER ROLE $DB_USERNAME SET search_path TO $DB_SCHEMA, public;
REVOKE ALL PRIVILEGES ON SCHEMA $DB_SCHEMA FROM public;
EOSQL

# POSTGRES_EXTENSIONS="
#     pg_stat_statements
#     plpgsql_check
#     pldbgapi
#     tablefunc
#     dblink
#     plpython3u
# "

POSTGRES_EXTENSIONS="
    pg_stat_statements
"
for ext in $POSTGRES_EXTENSIONS; do
    psql -e -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$DB_DATABASE" \
         -c "CREATE EXTENSION IF NOT EXISTS $ext SCHEMA $DB_SCHEMA;"
done
